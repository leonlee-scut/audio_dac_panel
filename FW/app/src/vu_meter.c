#include "vu_meter.h"
#include <math.h>
#include <string.h>

#define VU_ATTACK_MS     10.0f     /* 快速攻击 */
#define VU_RELEASE_MS   300.0f     /* 经典 VU 约 300 ms 到 99% */
#define PEAK_HOLD_MS   1200.0f
#define PEAK_DECAY_MS  1500.0f

static float db_to_linear(float db)
{
    return powf(10.0f, db / 20.0f);
}

static float linear_to_db(float lin)
{
    if (lin < 1e-8f) return -100.0f;
    return 20.0f * log10f(lin);
}

void VU_Init(VuMeter *vu, float sample_rate)
{
    memset(vu, 0, sizeof(*vu));
    vu->sample_rate = sample_rate;
}

void VU_SetSampleRate(VuMeter* vu, float sample_rate)
{
    vu->sample_rate = sample_rate;
}

void VU_ProcessBlock(VuMeter* vu, const int32_t* samples, uint32_t num_frames)
{
    if (num_frames == 0) return;

    float max_l = 0.0f, max_r = 0.0f;
    float sum_sq_l = 0.0f, sum_sq_r = 0.0f;

    for (uint32_t i = 0; i < num_frames; i++)
    {
        /* 24-bit 左对齐 → 有符号 32-bit，右移 8 位得到 24-bit 值 */
        int32_t sl = samples[i * 2] >> 8;
        int32_t sr = samples[i * 2 + 1] >> 8;

        float fl = (float)sl / 8388608.0f;   /* 2^23 */
        float fr = (float)sr / 8388608.0f;

        float al = fabsf(fl);
        float ar = fabsf(fr);

        if (al > max_l) max_l = al;
        if (ar > max_r) max_r = ar;

        sum_sq_l += fl * fl;
        sum_sq_r += fr * fr;
    }

    /* 使用峰值（更接近 VU 指针对瞬态的反应）也可改用 RMS */
    float block_l = max_l;
    float block_r = max_r;

    /* 指数弹道系数 */
    float dt = (float)num_frames / vu->sample_rate;
    float att = 1.0f - expf(-dt / (VU_ATTACK_MS / 1000.0f));
    float rel = 1.0f - expf(-dt / (VU_RELEASE_MS / 1000.0f));

    /* 左声道 */
    if (block_l > vu->left.level)
        vu->left.level += (block_l - vu->left.level) * att;
    else
        vu->left.level += (block_l - vu->left.level) * rel;

    if (block_l > vu->left.peak)
    {
        vu->left.peak = block_l;
        vu->left.peak_hold_ms = (uint32_t)PEAK_HOLD_MS;
    }
    else
    {
        if (vu->left.peak_hold_ms > 0)
        {
            uint32_t elapsed = (uint32_t)(dt * 1000.0f);
            if (vu->left.peak_hold_ms > elapsed)
                vu->left.peak_hold_ms -= elapsed;
            else
                vu->left.peak_hold_ms = 0;
        }
        else
        {
            float pdec = 1.0f - expf(-dt / (PEAK_DECAY_MS / 1000.0f));
            vu->left.peak += (vu->left.level - vu->left.peak) * pdec;
        }
    }

    /* 右声道（同样逻辑） */
    if (block_r > vu->right.level)
        vu->right.level += (block_r - vu->right.level) * att;
    else
        vu->right.level += (block_r - vu->right.level) * rel;

    if (block_r > vu->right.peak)
    {
        vu->right.peak = block_r;
        vu->right.peak_hold_ms = (uint32_t)PEAK_HOLD_MS;
    }
    else
    {
        if (vu->right.peak_hold_ms > 0)
        {
            uint32_t elapsed = (uint32_t)(dt * 1000.0f);
            if (vu->right.peak_hold_ms > elapsed)
                vu->right.peak_hold_ms -= elapsed;
            else
                vu->right.peak_hold_ms = 0;
        }
        else
        {
            float pdec = 1.0f - expf(-dt / (PEAK_DECAY_MS / 1000.0f));
            vu->right.peak += (vu->right.level - vu->right.peak) * pdec;
        }
    }
}

/* -40 dBFS → 0 列，0 dBFS → 100 列 */
static uint8_t db_to_col(float db)
{
    if (db < -40.0f) db = -40.0f;
    if (db > 0.0f) db = 0.0f;
    return (uint8_t)((db + 40.0f) * (100.0f / 40.0f) + 0.5f);
}

void VU_GetDisplay(const VuMeter* vu, uint8_t* left_cols, uint8_t* right_cols,
    uint8_t* left_peak_col, uint8_t* right_peak_col)
{
    float db_l = linear_to_db(vu->left.level);
    float db_r = linear_to_db(vu->right.level);
    float pk_l = linear_to_db(vu->left.peak);
    float pk_r = linear_to_db(vu->right.peak);

    *left_cols      = db_to_col(db_l);
    *right_cols     = db_to_col(db_r);
    *left_peak_col  = db_to_col(pk_l);
    *right_peak_col = db_to_col(pk_r);
}


