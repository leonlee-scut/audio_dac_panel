#ifndef __MEDIA_ICONS_H__
#define __MEDIA_ICONS_H__

#include <stdint.h>

/* Each byte is one row; the most significant bit is the leftmost pixel. */
static const uint8_t MEDIA_ICON_PLAY[8] = {
    0x20, 0x30, 0x38, 0x3C, 0x38, 0x30, 0x20, 0x00
};

static const uint8_t MEDIA_ICON_STOP[8] = {
    0x00, 0x7C, 0x7C, 0x7C, 0x7C, 0x7C, 0x00, 0x00
};

static const uint8_t MEDIA_ICON_FAST_FORWARD[8] = {
    0x24, 0x66, 0xEE, 0xEE, 0xEE, 0x66, 0x24, 0x00
};

static const uint8_t MEDIA_ICON_REWIND[8] = {
    0x24, 0xCC, 0xEE, 0xEE, 0xEE, 0xCC, 0x24, 0x00
};

static const uint8_t MEDIA_ICON_PAUSE[8] = {
    0x00, 0x6C, 0x6C, 0x6C, 0x6C, 0x6C, 0x00, 0x00
};

static const uint8_t MEDIA_ICON_MUSIC[8] = {
    0x18, 0x1C, 0x16, 0x13, 0x10, 0x30, 0x20, 0x00
};

#endif /* __MEDIA_ICONS_H__ */
